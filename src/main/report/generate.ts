import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import type { RunRecord, Severity } from '../../shared/engineTypes'

const SEVERITY_ORDER: Severity[] = ['critical', 'high', 'medium', 'low', 'info']

function fmtDate(timestamp?: number): string {
  if (!timestamp) return '—'
  return `${new Date(timestamp).toISOString().replace('T', ' ').slice(0, 19)} UTC`
}

function esc(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

function severityCounts(record: RunRecord): Record<Severity, number> {
  const counts: Record<Severity, number> = { critical: 0, high: 0, medium: 0, low: 0, info: 0 }
  for (const finding of record.findings) counts[finding.severity]++
  return counts
}

function evidenceJson(evidence: Record<string, unknown> | undefined): string {
  if (!evidence || Object.keys(evidence).length === 0) return ''
  return JSON.stringify(evidence, null, 2)
}

function logoDataUrl(): string | null {
  const candidates: string[] = []
  if (typeof process.resourcesPath === 'string' && process.resourcesPath.length > 0) {
    candidates.push(join(process.resourcesPath, 'logo.png'))
  }
  if (typeof __dirname === 'string') {
    candidates.push(join(__dirname, '../../resources/logo.png'))
  }
  candidates.push(join(process.cwd(), 'resources', 'logo.png'))
  for (const path of candidates) {
    try {
      if (existsSync(path)) {
        return `data:image/png;base64,${readFileSync(path).toString('base64')}`
      }
    } catch {
      // try next candidate
    }
  }
  return null
}

export function generateMarkdown(record: RunRecord): string {
  const counts = severityCounts(record)
  const lines: string[] = []

  lines.push('# SecurLab — Penetration Test Report', '')
  lines.push(`- **Chain**: ${record.chainTitle} (\`${record.chainId}\`)`)
  lines.push(`- **Target**: \`${record.target.host}:${record.target.port}\``)
  lines.push(`- **Started**: ${fmtDate(record.startedAt)}`)
  lines.push(`- **Finished**: ${fmtDate(record.endedAt)}`)
  lines.push(`- **Status**: ${record.status}`)
  if (record.error) lines.push(`- **Error**: ${record.error}`)
  const paramEntries = Object.entries(record.params).filter(([, value]) => value.length > 0)
  if (paramEntries.length > 0) {
    lines.push(`- **Parameters**: ${paramEntries.map(([k, v]) => `\`${k}=${v}\``).join(', ')}`)
  }
  lines.push('', record.chainDescription, '')

  lines.push('## Findings summary', '')
  lines.push('| Severity | Count |', '| --- | --- |')
  for (const severity of SEVERITY_ORDER) {
    lines.push(`| ${severity} | ${counts[severity]} |`)
  }
  lines.push('')

  if (record.findings.length > 0) {
    lines.push('## Findings', '')
    record.findings.forEach((finding, index) => {
      lines.push(`### ${index + 1}. [${finding.severity.toUpperCase()}] ${finding.title}`, '')
      lines.push(finding.detail, '')
      const evidence = evidenceJson(finding.evidence)
      if (evidence) {
        lines.push('**Evidence**', '', '```json', evidence, '```', '')
      }
    })
  } else {
    lines.push('## Findings', '', '_No findings were produced by this run._', '')
  }

  lines.push('## Steps', '')
  record.steps.forEach((step, index) => {
    lines.push(`### ${index + 1}. ${step.title} — ${step.status}`, '')
    lines.push(`- module: \`${step.module}\``)
    if (step.error) lines.push(`- error: ${step.error}`)
    if (step.logs.length > 0) {
      lines.push('', '**Log**', '', '```', ...step.logs.slice(0, 200), '```', '')
    }
    if (step.evidence.length > 0) {
      lines.push('', '**Evidence**', '', '```json')
      const merged: Record<string, unknown> = {}
      for (const item of step.evidence) merged[item.key] = item.value
      lines.push(JSON.stringify(merged, null, 2), '```', '')
    }
  })

  lines.push('---', '')
  lines.push(
    `Generated by SecurLab on ${fmtDate(Date.now())}. This report is intended for authorized security testing of systems you own or are permitted to test.`,
    ''
  )
  return lines.join('\n')
}

